"""Заглушка вместо pyannote.

Зачем она нужна. GigaAM-v3 приезжает с huggingface как удалённый код. Загружая такой
файл, transformers статически собирает **все** импорты в нём и требует, чтобы каждый
пакет импортировался, — даже если импорт лежит внутри функции, которая никогда не
вызовется. `pyannote` в том файле нужен ровно для одного: разметки длинной записи
через VAD (`transcribe_longform`). Короткий разбор его не трогает, а настоящий
`pyannote.audio` тянет за собой половину научного питона и всё равно требует ключ
`HF_TOKEN` для закрытой модели `pyannote/segmentation-3.0`.

Поэтому рядом лежит эта заглушка, и сторожевой процесс добавляет её в путь импорта,
только если настоящего pyannote в окружении нет. Если её всё-таки вызовут, будет
громкая понятная ошибка, а не тихая подмена поведения.
"""


def __getattr__(name: str):
    raise RuntimeError(
        f"pyannote.{name} вызван, а установлена заглушка: настоящий пакет не нужен для "
        "короткого разбора и не установлен. Он понадобится только для transcribe_longform."
    )
